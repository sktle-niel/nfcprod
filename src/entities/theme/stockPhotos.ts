/**
 * The photo library: ready-made page photos an owner can pick as the menu background, besides their own photo. A theme stores
 * only an id from this list. The files are ours (public/stock, served from the app's own address) and the address is built
 * from the id here, never from text a person typed. Each photo has a small thumbnail for the picker.
 * The photos are from Pexels, free to use without attribution. The credits are kept here and in CREDITS.md.
 */

/** The kinds of business the library is sorted by: the tabs of the picker. */
export const STOCK_CATEGORIES = ['coffee', 'milktea', 'casual', 'fine', 'bakery', 'bar'] as const
export type StockCategory = (typeof STOCK_CATEGORIES)[number]

/** How bright the photo is, to help an owner choose page and text colors that sit well on it. */
export type StockTone = 'dark' | 'mid' | 'light'

export type StockPhoto = {
  id: string
  /** The file without folder prefix or extension: public/stock/<file>.jpg and public/stock/<file>.thumb.jpg. */
  file: string
  category: StockCategory
  /** What the photo shows, for a screen reader. */
  alt: string
  tone: StockTone
  /** The size of the file in pixels. The renderer needs the width to know whether a screen is too wide for it. */
  width: number
  height: number
  /** The photographer, for the credit line. */
  credit: string
  /** The photo's page on Pexels. */
  source: string
}

